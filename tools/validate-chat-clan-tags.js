"use strict";
const assert = require("node:assert/strict");
const { createClanTagLookup, setClanTag } = require("../chat-ui");
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  let time = 1, realm = "first", calls = [], fail = false, changes = 0;
  const rows = new Map([["alice", { id: "alice", clanId: "one", clanTag: "CODE" }], ["bob", { id: "bob", clanTag: "STALE" }]]);
  const tags = createClanTagLookup({ now: () => time, scope: () => realm, onChange: () => changes++,
    load: async ids => { calls.push(ids); if (fail) throw Error("Disconnected"); return ids.map(id => rows.get(id)).filter(Boolean); } });
  await tags.refresh(["alice", "alice", "bob", "missing", "../forged"]);
  assert.deepEqual(calls, [["alice", "bob", "missing"]]);
  assert.equal(tags.get("alice"), "CODE"); assert.equal(tags.get("bob"), ""); assert.equal(tags.get("missing"), "");
  await tags.refresh(["alice", "missing"]); assert.equal(calls.length, 1, "Deduplicate names and missing public identities");
  time += 60000; rows.set("alice", { id: "alice", clanId: "two", clanTag: "NEW" });
  assert.equal(tags.get("alice"), "", "Expired membership must not stay visible");
  await tags.refresh(["alice"]); assert.equal(tags.get("alice"), "NEW");
  time += 60000; rows.set("alice", { id: "alice" });
  await tags.refresh(["alice"]); assert.equal(tags.get("alice"), "", "Leaving a clan removes its tag");
  time += 60000; fail = true; await tags.refresh(["alice"]); assert.equal(tags.get("alice"), "");
  const failedCalls = calls.length; await tags.refresh(["alice"]); assert.equal(calls.length, failedCalls, "Failures do not create a retry storm");
  time += 60000; fail = false; rows.set("alice", { uid: "alice", clanId: "two", clanTag: "BACK" });
  await tags.refresh(["alice"]); assert.equal(tags.get("alice"), "BACK", "Recover on next refresh");
  realm = "next"; assert.equal(tags.get("alice"), "", "Realm changes clear previous identities");
  await tags.refresh(["alice"]); assert.equal(tags.get("alice"), "BACK");
  let release, active = 0, maximum = 0;
  const delayed = createClanTagLookup({ scope: () => realm, load: async ids => {
    active++; maximum = Math.max(maximum, active);
    await new Promise(resolve => { release = resolve; }); active--;
    return ids.map(id => ({ id, clanId: "old", clanTag: "OLD" }));
  } });
  const first = delayed.refresh(Array.from({ length: 25 }, (_, i) => "p" + i));
  delayed.refresh(["p1", "p26"]); await flush();
  release(); await flush(); release(); await flush(); release(); await first;
  assert.equal(maximum, 1, "Only one batch is in flight"); assert.equal(delayed.get("p26"), "OLD");
  delayed.reset(); const old = delayed.refresh(["alice"]); await flush();
  realm = "changed-while-loading"; release(); await old;
  assert.equal(delayed.get("alice"), "", "Late replies cannot repopulate a different realm/account");
  const resetLoad = delayed.refresh(["bob"]); await flush(); delayed.reset(); release(); await resetLoad;
  assert.equal(delayed.get("bob"), "", "Logout discards in-flight results");
  let visible = true, batches = 0, unblock;
  const paused = createClanTagLookup({ active: () => visible, load: async () => { batches++; await new Promise(resolve => { unblock = resolve; }); return []; } });
  const loading = paused.refresh(Array.from({ length: 15 }, (_, i) => "p" + i));
  visible = false; unblock(); await loading;
  assert.equal(batches, 1, "Closing or hiding chat stops queued identity batches");
  visible = true; const resumed = paused.refresh(["p14"]); await flush(); unblock(); await resumed;
  assert.equal(batches, 2, "Reopening resumes the bounded queue");
  calls = []; tags.reset(); await tags.refresh(Array.from({ length: 600 }, (_, i) => "p" + i));
  assert(calls.every(batch => batch.length <= 10)); assert(calls.flat().length <= 200, "Bound the identity working set to rendered history");
  const node = { setAttribute(key, value) { this[key] = value; } };
  setClanTag(node, "<img>"); assert.equal(node.textContent, "[<img>]"); assert.equal(node.hidden, false);
  setClanTag(node, ""); assert.equal(node.textContent, ""); assert.equal(node.hidden, true);
  assert(changes > 1); console.log("Chat clan tags: bounded lookup, current membership, expiry, failure recovery, scope/reply isolation and safe text passed.");
})().catch(error => { console.error(error); process.exitCode = 1; });
