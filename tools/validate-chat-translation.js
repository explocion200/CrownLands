const assert = require("node:assert/strict");
const { create, preferredLanguage, isForeign, hasLanguage } = require("../chat-translation");
const tick = () => new Promise(resolve => setImmediate(resolve));
const message = (id, text = "Bonjour") => Object.freeze({ id, text });
const view = (messages, channel = "global", clanId = "") => ({ messages, channel, clanId, active: true });
async function main() {
  assert.equal(preferredLanguage(["es-MX"]), "es");
  assert.equal(preferredLanguage(["zh-Hant-HK"]), "zh-TW");
  assert.equal(preferredLanguage(["zh-CN"]), "zh-CN");
  assert.equal(preferredLanguage(["bad_tag", "fr-CA"]), "fr");
  assert.equal(preferredLanguage([], "bad_tag"), "en");
  assert(!hasLanguage("12:30 (42, 18) ⚔️") && !hasLanguage("https://example.com"));
  assert(hasLanguage("你好") && hasLanguage("Hola"));
  assert(!isForeign("en", 1, "en") && !isForeign("es", .2, "en") && !isForeign("und", 1, "en"));
  assert(isForeign("es", .9, "en") && !isForeign("zh", .9, "zh-TW"));
  const a=message("a"), b=message("b", "Good morning"), c=message("c", "123"), d=message("d", "??? ambiguous");
  const context=view([a,b,c,d]);
  let calls=[], fail=false, resolveTranslation;
  const engine=create({language:"en",translate:async payload=>{
    calls.push(payload);
    assert(!Object.hasOwn(payload,"text"),"Only authoritative message IDs go to the server");
    if(payload.operation==="detect")return {detections:payload.messageIds.map(id=>({id,language:id==="b"?"en":"fr",confidence:id==="d"?.2:.99}))};
    if(fail)throw Object.assign(Error("Unavailable"),{details:{reason:"translation-monthly-limit"}});
    return new Promise(resolve=>{resolveTranslation=resolve;});
  }});
  engine.setAccount("alice");
  engine.update({...context,active:false});await tick();assert.equal(calls.length,0);
  engine.update(context);await tick();
  assert.equal(calls.length,1);assert.equal(calls[0].operation,"detect");
  assert(!calls[0].messageIds.includes("c"));
  assert(engine.display(a,context).eligible);
  for(const msg of [b,c,d])assert(!engine.display(msg,context).eligible);
  assert.equal(engine.display(a,context).text,a.text,"Detection must not translate");
  const pending=engine.toggle(a,context);await tick();
  assert.deepEqual(calls[1],{channel:"global",clanId:"",messageIds:["a"],targetLanguage:"en"});
  assert.equal(engine.display(a,context).state,"pending");
  assert.equal(engine.display(a,context).text,a.text);
  resolveTranslation({translations:[{id:"a",text:"Hello"}]});await pending;
  assert.equal(engine.display(a,context).text,"Hello");
  await engine.toggle(a,context);assert.equal(engine.display(a,context).text,a.text);
  await engine.toggle(a,context);assert.equal(engine.display(a,context).text,"Hello");
  assert.equal(calls.length,2,"Show original and cached translation are local");
  engine.update(view([a,b,c,d,message("new")]));await tick();
  assert.equal(calls.at(-1).operation,"detect","New messages remain original until clicked");
  fail=true;
  await engine.toggle(message("new"),view([]));
  assert.equal(engine.display(message("new"),context).state,"error");
  assert(engine.display(message("new"),context).monthlyLimit);
  assert.equal(engine.display(a,context).text,"Hello","One row's failure must not change another");
  fail=false;
  const retry=engine.toggle(message("new"),view([]));await tick();
  resolveTranslation({translations:[{id:"new",text:"New result"}]});await retry;
  assert.equal(engine.display(message("new"),context).text,"New result");
  engine.update(view([message("stale")]));await tick();
  const stale=engine.toggle(message("stale"),context);await tick();
  const resolveStale=resolveTranslation;
  engine.setAccount("bob");
  resolveStale({translations:[{id:"stale",text:"Alice private result"}]});await stale;
  assert.equal(engine.display(message("stale"),context).text,"Bonjour");
  engine.dispose();

  const resolvers=[], requests=[];
  const switching=create({language:"en",translate:payload=>{requests.push(payload);return new Promise(resolve=>resolvers.push(resolve));}});
  switching.setAccount("a");switching.update(view([a]));await tick();
  switching.setLanguage("es");await tick();
  resolvers[0]({detections:[{id:"a",language:"es",confidence:1}]});
  resolvers[1]({detections:[{id:"a",language:"fr",confidence:1}]});await tick();
  assert(switching.display(a,context).eligible);
  const chosen=switching.toggle(a,context);await tick();
  switching.update(view([a],"clan","new-clan"));await tick();
  resolvers[2]({translations:[{id:"a",text:"Stale channel"}]});await chosen;
  assert.equal(switching.display(a,context).text,"Bonjour","Channel switch cancels a pending result");
  resolvers[3]({detections:[{id:"a",language:"fr",confidence:1}]});await tick();
  switching.clear();assert(!switching.display(a,view([],"clan","new-clan")).eligible);
  switching.dispose();

  const batches=[];
  const batcher=create({translate:async payload=>{batches.push(payload.messageIds.length);return {detections:payload.messageIds.map(id=>({id,language:"fr",confidence:1}))};}});
  batcher.setAccount("a");batcher.update(view(Array.from({length:45},(_,i)=>message(String(i)))));
  await tick();await tick();assert.deepEqual(batches,[20,20,5]);batcher.dispose();
  const timer=create({timeoutMs:5,translate:async payload=>payload.operation==="detect"?{detections:[{id:"a",language:"fr",confidence:1}]}:new Promise(()=>{})});
  timer.setAccount("a");timer.update(context);await tick();await timer.toggle(a,context);
  assert.equal(timer.display(a,context).state,"error");timer.dispose();
  console.log("Individual translation passed: device language, authoritative detection, neutral/uncertain suppression, no automatic translation, single-message requests, originals, caching, row-local quota/retry, account/channel isolation, batching and timeout.");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
