const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const projectRoot = path.resolve(__dirname, "..");
const worldRoot = path.join(projectRoot, "assets", "worlds", "world_01");
const mapsRoot = path.join(worldRoot, "maps");
const versionedRoot = path.join(mapsRoot, "versioned");
const layoutPath = path.join(worldRoot, "world-layout.json");
const manifestPath = path.join(worldRoot, "map-manifest.json");

const referenceFiles = [
  "game.js",
  "assets/map-editor-data.js",
  "functions/world-layout.json",
  "assets/worlds/world_01/world-layout.json",
  ...fs.readdirSync(path.join(worldRoot, "regions"))
    .filter(name => name.endsWith(".json"))
    .sort()
    .map(name => `assets/worlds/world_01/regions/${name}`),
];

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8").replace(/^\uFEFF/, ""));
}

function sha256(payload) {
  return crypto.createHash("sha256").update(payload).digest("hex");
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function existingSourceByRegion() {
  if (!fs.existsSync(manifestPath)) return new Map();
  const manifest = readJson(manifestPath);
  return new Map((manifest.maps || []).map(entry => [entry.id, entry.source]));
}

function createMapEntries({ write }) {
  const layout = readJson(layoutPath);
  const priorSources = existingSourceByRegion();
  if (write) fs.mkdirSync(versionedRoot, { recursive: true });

  return layout.regions.map(region => {
    const currentPath = String(region.imagePath || "");
    const source = currentPath.includes("/maps/versioned/")
      ? priorSources.get(region.id)
      : currentPath;
    if (!source || source.includes("/maps/versioned/")) {
      throw new Error(`${region.id} has no editable world-map source.`);
    }
    const sourcePath = path.join(projectRoot, source);
    if (!fs.existsSync(sourcePath)) throw new Error(`${region.id} source map is missing: ${source}.`);
    const payload = fs.readFileSync(sourcePath);
    const digest = sha256(payload);
    const stem = path.basename(source, path.extname(source));
    const outputName = `${stem}-${digest.slice(0, 12)}.webp`;
    const output = `assets/worlds/world_01/maps/versioned/${outputName}`;
    const outputPath = path.join(projectRoot, output);
    if (write && (!fs.existsSync(outputPath) || sha256(fs.readFileSync(outputPath)) !== digest)) {
      fs.copyFileSync(sourcePath, outputPath);
    }
    if (!write && (!fs.existsSync(outputPath) || sha256(fs.readFileSync(outputPath)) !== digest)) {
      throw new Error(`${region.id} immutable runtime map is missing or stale: ${output}.`);
    }
    return { id: region.id, source, output, bytes: payload.length, sha256: digest };
  });
}

function updateReferences(entries, { write }) {
  for (const relativePath of referenceFiles) {
    const absolutePath = path.join(projectRoot, relativePath);
    const original = fs.readFileSync(absolutePath, "utf8");
    let updated = original;
    for (const entry of entries) {
      const sourceStem = path.basename(entry.source, ".webp");
      const pattern = new RegExp(
        `assets/worlds/world_01/maps/(?:versioned/)?${escapeRegExp(sourceStem)}(?:-[0-9a-f]{12})?\\.webp`,
        "g",
      );
      updated = updated.replace(pattern, entry.output);
    }
    if (!write && updated !== original) {
      throw new Error(`${relativePath} does not reference the current immutable world maps.`);
    }
    if (write && updated !== original) fs.writeFileSync(absolutePath, updated, "utf8");
  }
}

function writeManifest(entries, { write }) {
  const payload = `${JSON.stringify({
    schemaVersion: 1,
    description: "Immutable gameplay maps generated byte-for-byte from the restored editable regional sources.",
    maps: entries,
  }, null, 2)}\n`;
  if (!write) {
    const current = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== payload.replace(/\r\n/g, "\n")) throw new Error("assets/worlds/world_01/map-manifest.json is stale.");
    return;
  }
  fs.writeFileSync(manifestPath, payload, "utf8");
}

function removeStaleVersionedMaps(entries, { write }) {
  if (!write || !fs.existsSync(versionedRoot)) return;
  const current = new Set(entries.map(entry => path.basename(entry.output)));
  for (const name of fs.readdirSync(versionedRoot)) {
    if (!/\.webp$/i.test(name) || current.has(name)) continue;
    fs.unlinkSync(path.join(versionedRoot, name));
  }
}

function fingerprintWorldMaps({ checkOnly = false } = {}) {
  const options = { write: !checkOnly };
  const entries = createMapEntries(options);
  if (entries.length !== 20) throw new Error(`Expected 20 regional maps, found ${entries.length}.`);
  updateReferences(entries, options);
  writeManifest(entries, options);
  removeStaleVersionedMaps(entries, options);
  return entries;
}

if (require.main === module) {
  const checkOnly = process.argv.includes("--check");
  const entries = fingerprintWorldMaps({ checkOnly });
  const bytes = entries.reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(`${checkOnly ? "Validated" : "Fingerprint-stamped"} ${entries.length} gameplay maps (${bytes.toLocaleString("en-US")} bytes).`);
}

module.exports = { fingerprintWorldMaps };
