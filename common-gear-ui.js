function createCommonGearUpgradeContext(instances) {
  const counts = new Map(), ids = new Set();
  for (const item of instances) {
    const key = `${item.gearKey}:${item.level}`;
    const row = counts.get(key) || { stored: 0, equipped: 0 };
    row[item.isEquipped ? "equipped" : "stored"] += 1;
    counts.set(key, row); ids.add(item.instanceId);
  }
  return { counts, ids };
}

function getCommonGearUpgradePreview(instance, instances = Object.values(state?.gear?.instances || {}), context = null) {
  if (!instance) {
    return {
      requirement: null,
      duplicateCount: 0,
      upgradeGold: 0,
      hasMatchingMaterial: false,
      hasEnoughGold: false,
      canUpgrade: false,
      reason: "Select an item to upgrade.",
    };
  }
  const requirement = COMMON_GEAR.getUpgradeRequirement(instance);
  if (!requirement) {
    return {
      requirement: null,
      duplicateCount: 0,
      upgradeGold: 0,
      hasMatchingMaterial: false,
      hasEnoughGold: false,
      canUpgrade: false,
      reason: "Max level.",
    };
  }
  const shared = context || createCommonGearUpgradeContext(instances);
  const counts = shared.counts.get(`${instance.gearKey}:${instance.level}`) || { stored: 0, equipped: 0 };
  const duplicateCount = Math.max(0, counts.stored - (!instance.isEquipped && shared.ids.has(instance.instanceId) ? 1 : 0));
  const matchingEquippedCount = Math.max(0, counts.equipped - (instance.isEquipped && shared.ids.has(instance.instanceId) ? 1 : 0));
  const upgradeGold = COMMON_GEAR.getUpgradeGoldCost(instance);
  const hasMatchingMaterial = duplicateCount >= requirement.duplicates;
  const hasEnoughGold = Math.max(0, Number(state?.gold) || 0) >= upgradeGold;
  const issues = [];
  if (!hasMatchingMaterial) {
    issues.push(`No matching material. Requires ${requirement.duplicates} matching Level ${instance.level} cop${requirement.duplicates === 1 ? "y" : "ies"}; ${duplicateCount} available.`);
    if (!instance.isEquipped && matchingEquippedCount > 0) {
      issues.push(`Select the equipped Level ${instance.level} copy as the upgrade target; equipped gear cannot be used as material.`);
    }
  }
  if (!hasEnoughGold) {
    issues.push(`Insufficient gold. Requires ${formatNumber(upgradeGold)} gold; ${formatNumber(state?.gold)} available.`);
  }
  return {
    requirement,
    duplicateCount,
    upgradeGold,
    hasMatchingMaterial,
    hasEnoughGold,
    canUpgrade: hasMatchingMaterial && hasEnoughGold,
    reason: issues.join(" "),
  };
}

