const commonGearUpgradeRequests = new Map();
let commonGearActiveAction = null;

function getCommonGearActionScope() {
  return typeof getOnlineSessionRequestScope === "function" ? getOnlineSessionRequestScope() : "local";
}

async function runCommonGearAction(buildingId, action, instanceId, quotedCost = undefined) {
  const scope = getCommonGearActionScope();
  if ((commonGearActionInFlight && commonGearActiveAction?.scope === scope) || !instanceId) return;
  const instance = state?.gear?.instances?.[instanceId];
  const definition = instance ? COMMON_GEAR.getDefinition(instance.gearKey) : null;
  if (!instance || !definition) return showToast("That gear piece is no longer available.");
  const token = { scope, state };
  const isCurrent = () => token.state === state && token.scope === getCommonGearActionScope();
  const accountScope = typeof getOnlineRequestScope === "function" ? getOnlineRequestScope() : scope;
  const retryKey = `${accountScope}:${instanceId}`;
  commonGearActiveAction = token;
  commonGearActionInFlight = true;
  commonGearMergeConfirmOpen = false;
  commonGearViewRequestId += 1;
  if (isCommonGearBuildingOpen(buildingId)) renderCommonGearBuilding(buildingId);
  try {
    const api = getOnlineApi();
    let result = null;
    if (action === "unequip") {
      if (!api?.unequipCommonGear) throw new Error("Connect to the realm to change this loadout.");
      result = await api.unequipCommonGear({ instanceId });
    } else if (action === "equip") {
      if (!api?.equipCommonGear) throw new Error("Connect to the realm to change this loadout.");
      result = await api.equipCommonGear({ instanceId });
    } else {
      if (!api?.upgradeCommonGear) throw new Error("Connect to the realm to upgrade equipment.");
      let pending = commonGearUpgradeRequests.get(retryKey);
      if (!pending) {
        pending = { instanceId, requestId: createDailyMissionRequestId("gear-upgrade"),
          cost: Number.isFinite(quotedCost) ? quotedCost : getCommonGearUpgradePreview(instance).upgradeGold };
        commonGearUpgradeRequests.set(retryKey, pending);
        if (commonGearUpgradeRequests.size > 24) commonGearUpgradeRequests.delete(commonGearUpgradeRequests.keys().next().value);
      }
      result = await api.upgradeCommonGear(pending);
      commonGearUpgradeRequests.delete(retryKey);
    }
    if (!isCurrent()) return;
    applyServerEconomyResult(result);
    if (action === "merge") playGoldSpendSound(result?.spentGold, result);
    if (action === "merge") {
      if (definition.category === "armor"
          && result?.upgradedInstanceId && result?.ok !== false && !result?.replayed && !result?.duplicate) {
        try {
          if (definition.buildingId === "treasury") {
            playGameSound("treasury_armor_upgrade", { allowCrossMap: true, delayMs: 150 });
          } else {
            playGameSound("chainmail_armor_upgrade", { allowCrossMap: true, delayMs: 150 });
          }
        } catch (error) {
          console.warn("Could not play confirmed armor upgrade sound", error);
        }
      }
      const responseGear = result?.currentUser?.gear || result?.gear;
      if (responseGear && Number(responseGear.updatedAtMs || 0) >= Number(state?.gear?.updatedAtMs || 0)) {
        state.gear = normalizeCommonGearState(responseGear);
      }
      const upgradedInstanceId = String(result?.upgradedInstanceId || "");
      if (state?.gear?.instances?.[upgradedInstanceId]) selectedCommonGearInstanceId = upgradedInstanceId;
      const consumedInstanceIds = Array.isArray(result?.consumedInstanceIds) ? result.consumedInstanceIds : [];
      if (consumedInstanceIds.some(consumedId => state?.gear?.instances?.[consumedId])) {
        const refreshed = await api.viewCommonGearBuilding?.({ buildingId });
        if (!isCurrent()) return;
        if (refreshed?.gear) state.gear = normalizeCommonGearState(refreshed.gear);
      }
      const settledInstance = state?.gear?.instances?.[upgradedInstanceId];
      const receipt = result?.upgradeReceipt;
      const rarity = settledInstance?.rarity || receipt?.newRarity || definition.rarity;
      const level = settledInstance?.level || receipt?.newLevel;
      showToast(`${definition.gearName} upgraded${level ? ` to ${titleCaseCommonGearLabel(rarity)} Level ${level}` : ""}. Both input items were consumed.`);
    } else showToast(`${definition.gearName} ${action === "equip" ? "equipped" : "returned to the bag"}.`);
  } catch (error) {
    const code = String(error?.code || "");
    if (/(invalid-argument|failed-precondition|not-found|permission-denied|resource-exhausted)$/.test(code)) {
      commonGearUpgradeRequests.delete(retryKey);
    }
    if (isCurrent()) showToast(error?.message || (action === "merge" ? "The gear upgrade could not be completed." : "The gear loadout could not be changed."));
  } finally {
    if (commonGearActiveAction === token) {
      commonGearActionInFlight = false;
      commonGearActiveAction = null;
    }
    if (isCurrent() && isCommonGearBuildingOpen(buildingId)) renderCommonGearBuilding(buildingId);
  }
}

function bindCommonGearScreen(viewModel) {
  const screen = modalBody.querySelector("[data-common-gear-screen]");
  const bagScroll = modalBody.querySelector("[data-gear-bag-scroll]");
  const detailsScroll = modalBody.querySelector('[data-gear-panel="details"]');
  if (!screen) return;
  if (bagScroll) {
    bagScroll.scrollTop = commonGearBagScrollTop;
    bagScroll.addEventListener("scroll", () => { commonGearBagScrollTop = bagScroll.scrollTop; }, { passive: true });
  }
  detailsScroll?.addEventListener("keydown", event => {
    if (event.target !== detailsScroll || !["Home", "End", "PageUp", "PageDown"].includes(event.key)) return;
    const maxScrollTop = Math.max(0, detailsScroll.scrollHeight - detailsScroll.clientHeight);
    const pageStep = Math.max(1, Math.floor(detailsScroll.clientHeight * .8));
    const nextScrollTop = event.key === "Home" ? 0
      : event.key === "End" ? maxScrollTop
        : detailsScroll.scrollTop + (event.key === "PageUp" ? -pageStep : pageStep);
    event.preventDefault();
    detailsScroll.scrollTop = Math.max(0, Math.min(maxScrollTop, nextScrollTop));
  });
  screen.querySelector("[data-gear-bag-select]")?.addEventListener("change", event => {
    const value = event.target.value;
    selectedCommonGearBagFilter = COMMON_GEAR.SLOTS.includes(value) ? value : "all";
    commonGearPendingFocusSelector = "[data-gear-bag-select]";
    renderCommonGearBuilding(viewModel.buildingId);
  });
  screen.addEventListener("keydown", event => {
    if (["treasury", "barracks", "gatehouse", "royal-stables"].includes(viewModel.buildingId) && viewModel.mergeConfirmOpen && event.key === "Tab") {
      const first = screen.querySelector("[data-gear-merge-cancel]");
      const last = screen.querySelector("[data-gear-merge-confirm]");
      if (event.shiftKey && event.target === first) {
        event.preventDefault();
        last?.focus();
      } else if (!event.shiftKey && event.target === last) {
        event.preventDefault();
        first?.focus();
      }
      return;
    }
    const filterButton = event.target.closest?.("[data-gear-bag-filter-button]");
    if (filterButton && event.key === "ArrowDown") {
      event.preventDefault();
      setCommonGearBagFilterOpen(screen, true, { focusSelectedOption: true });
      return;
    }
    const option = event.target.closest?.("[data-gear-bag-filter-option]");
    if (!option) return;
    const options = [...screen.querySelectorAll("[data-gear-bag-filter-option]")];
    const currentIndex = options.indexOf(option);
    let nextIndex = currentIndex;
    if (event.key === "ArrowDown") nextIndex = Math.min(options.length - 1, currentIndex + 1);
    else if (event.key === "ArrowUp") nextIndex = Math.max(0, currentIndex - 1);
    else if (event.key === "Home") nextIndex = 0;
    else if (event.key === "End") nextIndex = options.length - 1;
    else if (event.key === "Escape") {
      event.preventDefault();
      setCommonGearBagFilterOpen(screen, false);
      filterButton?.focus();
      screen.querySelector("[data-gear-bag-filter-button]")?.focus();
      return;
    } else return;
    event.preventDefault();
    options[nextIndex]?.focus();
  });
  screen.addEventListener("focusout", event => {
    const filter = event.target.closest?.("[data-gear-bag-filter]");
    if (!filter || filter.contains(event.relatedTarget)) return;
    setCommonGearBagFilterOpen(screen, false);
  });
  screen.addEventListener("click", event => {
    const filterButton = event.target.closest?.("[data-gear-bag-filter-button]");
    if (filterButton) {
      setCommonGearBagFilterOpen(screen, !commonGearBagFilterOpen);
      return;
    }
    const filterOption = event.target.closest?.("[data-gear-bag-filter-option]");
    if (filterOption) {
      const value = filterOption.dataset.gearBagFilterOption;
      selectedCommonGearBagFilter = value === "all" || COMMON_GEAR.SLOTS.includes(value) ? value : "all";
      commonGearBagFilterOpen = false;
      commonGearPendingFocusSelector = "[data-gear-bag-filter-button]";
      renderCommonGearBuilding(viewModel.buildingId);
      return;
    }
    if (commonGearBagFilterOpen && !event.target.closest?.("[data-gear-bag-filter]")) {
      setCommonGearBagFilterOpen(screen, false);
    }
    const slotButton = event.target.closest?.("[data-gear-slot]");
    if (slotButton) {
      selectedCommonGearSlot = COMMON_GEAR.SLOTS.includes(slotButton.dataset.gearSlot) ? slotButton.dataset.gearSlot : "head";
      const equippedId = state.gear.equipped?.[viewModel.buildingId]?.[selectedCommonGearSlot] || "";
      selectedCommonGearInstanceId = state.gear.instances?.[equippedId]?.instanceId
        || getCommonGearInstances(viewModel.buildingId, selectedCommonGearSlot)[0]?.instanceId
        || "";
      commonGearMergeConfirmOpen = false;
      commonGearPendingFocusSelector = `[data-gear-slot="${selectedCommonGearSlot}"]`;
      renderCommonGearBuilding(viewModel.buildingId);
      return;
    }
    const itemButton = event.target.closest?.("[data-gear-instance]");
    if (itemButton) {
      const instance = state.gear.instances?.[itemButton.dataset.gearInstance];
      if (!instance || instance.buildingId !== viewModel.buildingId) return;
      selectedCommonGearInstanceId = instance.instanceId;
      selectedCommonGearSlot = instance.slot;
      commonGearMergeConfirmOpen = false;
      commonGearPendingFocusSelector = `[data-gear-instance="${instance.instanceId}"]`;
      renderCommonGearBuilding(viewModel.buildingId);
      return;
    }
    if (event.target.closest?.("[data-gear-back]")) {
      const cityId = modal.dataset.innerCastleCityId || state.mainCityId;
      delete modal.dataset.commonGearBuildingId;
      modal.classList.remove("common-gear-building-modal");
      modal.classList.add("inner-castle-modal");
      commonGearMergeConfirmOpen = false;
      commonGearBagFilterOpen = false;
      commonGearPendingFocusSelector = "";
      commonGearViewRequestId += 1;
      renderInnerCastle(cityId);
      return;
    }
    if (event.target.closest?.("[data-gear-equip]")) {
      const selected = state.gear.instances?.[selectedCommonGearInstanceId];
      if (selected) void runCommonGearAction(viewModel.buildingId, selected.isEquipped ? "unequip" : "equip", selected.instanceId);
      return;
    }
    if (event.target.closest?.("[data-gear-merge]")) {
      if (!viewModel.canMerge || commonGearActionInFlight) return;
      commonGearMergeConfirmOpen = true;
      commonGearPendingFocusSelector = "[data-gear-merge-cancel]";
      renderCommonGearBuilding(viewModel.buildingId);
      return;
    }
    if (event.target.closest?.("[data-gear-merge-cancel]")) {
      commonGearMergeConfirmOpen = false;
      commonGearPendingFocusSelector = "[data-gear-merge]";
      renderCommonGearBuilding(viewModel.buildingId);
      return;
    }
    if (event.target.closest?.("[data-gear-merge-confirm]")) {
      commonGearPendingFocusSelector = "[data-gear-merge]";
      void runCommonGearAction(viewModel.buildingId, "merge", selectedCommonGearInstanceId, viewModel.upgradeGold);
    }
  });
}

